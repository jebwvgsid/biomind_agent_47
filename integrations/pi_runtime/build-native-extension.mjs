/** Bundle only BioMind; Pi supplies its public modules to the native extension. */
import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const runtime = path.dirname(fileURLToPath(import.meta.url));
await build({
  absWorkingDir: runtime,
  entryPoints: {
    'biomind-extension': 'dist/extensions/biomind.js',
    'output-limits-extension': 'dist/vendor/pi-output-limits/src/index.js',
    // Synthetic CLI tests must not reintroduce the duplicate SDK themselves.
    'native-fixture': 'dist/testing/native-fixture.js',
  },
  outdir: 'dist',
  outExtension: { '.js': '.ts' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  packages: 'external',
  sourcemap: 'linked',
  sourcesContent: false,
  // Pi 0.87.1's Jiti loader native-imports ESM .js files, bypassing its
  // embedded SDK. A .ts entry uses the public virtual modules instead.
  // Keep this bundle in dist/: domain-client, project-launcher and
  // canary-budget resolve runtime files relative to that directory.
  banner: { js: '// Generated by build-native-extension.mjs. Do not edit.' },
});
