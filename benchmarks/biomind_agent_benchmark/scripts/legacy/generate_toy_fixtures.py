def simulate_assembly(cfg: FixtureConfig) -> None:
    rng = np.random.default_rng(cfg.seed + 5)
    out = ensure_dir(cfg.outdir / "assembly")
    genome = "".join(rng.choice(DNA_ALPHABET, size=120_000).tolist())
    write_fasta([("toy_chr1", genome)], out / "toy_reference.fa")
    records = []
    for i in range(1, 81):
        length = int(rng.integers(2500, 9000))
        start = int(rng.integers(0, len(genome) - length))
        read = mutate_dna(genome[start : start + length], rng, 0.01)
        qual = "I" * len(read)
        records.append((f"toy_hifi_read_{i:04d}/start={start}", read, qual))
    write_fastq(records, out / "toy_hifi_reads.fastq")
    write_tsv(
        pd.DataFrame(
            {
                "reference_id": ["toy_chr1"],
                "length_bp": [len(genome)],
                "read_count": [len(records)],
                "mean_read_length": [round(float(np.mean([len(r[1]) for r in records])), 2)],
                "simulated_error_rate": [0.01],
            }
        ),
        out / "assembly_truth.tsv",
    )


def simulate_bulk_rnaseq(cfg: FixtureConfig) -> None:
    rng = np.random.default_rng(cfg.seed + 6)
    out = ensure_dir(cfg.outdir / "bulk_rnaseq")
    genes = [f"BR_GENE_{i:04d}" for i in range(1, 501)]
    samples = [f"ctrl_{i}" for i in range(1, 4)] + [f"stress_{i}" for i in range(1, 4)]
    base = rng.gamma(2.2, 80, size=len(genes))
    counts = np.vstack([rng.poisson(base) for _ in samples]).T
    de_idx = np.arange(30)
    counts[np.ix_(de_idx, np.arange(3, 6))] = (counts[np.ix_(de_idx, np.arange(3, 6))] * 3.0).astype(int)
    count_df = pd.DataFrame(counts, columns=samples)
    count_df.insert(0, "gene_id", genes)
    write_tsv(count_df, out / "count_matrix.tsv")
    tpm = counts / counts.sum(axis=0, keepdims=True) * 1_000_000
    tpm_df = pd.DataFrame(np.round(tpm, 3), columns=samples)
    tpm_df.insert(0, "gene_id", genes)
    write_tsv(tpm_df, out / "tpm_matrix.tsv")
    write_tsv(
        pd.DataFrame(
            {
                "sample_id": samples,
                "condition": ["ctrl"] * 3 + ["stress"] * 3,
                "replicate": [1, 2, 3, 1, 2, 3],
            }
        ),
        out / "metadata.tsv",
    )
    write_tsv(
        pd.DataFrame(
            {
                "gene_id": genes,
                "symbol": [f"BRG{i:04d}" for i in range(1, len(genes) + 1)],
                "description": ["synthetic crop gene"] * len(genes),
            }
        ),
        out / "annotation.tsv",
    )
    write_tsv(
        pd.DataFrame(
            {
                "gene_id": [genes[i] for i in de_idx],
                "expected_log2fc": [round(math.log2(3.0), 3)] * len(de_idx),
                "direction": ["up_in_stress"] * len(de_idx),
            }
        ),
        out / "truth_de_genes.tsv",
    )


