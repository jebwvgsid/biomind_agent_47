BENCHMARK_DIR = Path(__file__).resolve().parents[2]
DEFAULT_OUTDIR = BENCHMARK_DIR / "fixtures"


DNA_ALPHABET = np.array(list("ACGT"))
AA_ALPHABET = np.array(list("ACDEFGHIKLMNPQRSTVWY"))


@dataclass(frozen=True)
class FixtureConfig:
    seed: int = 20260526
    outdir: Path = DEFAULT_OUTDIR


def ensure_dir(path: Path) -> Path:
    path.mkdir(parents=True, exist_ok=True)
    return path


def write_tsv(df: pd.DataFrame, path: Path, index: bool = False) -> None:
    ensure_dir(path.parent)
    df.to_csv(path, sep="\t", index=index)


def write_fasta(records: list[tuple[str, str]], path: Path, line_width: int = 80) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8") as handle:
        for name, seq in records:
            handle.write(f">{name}\n")
            for i in range(0, len(seq), line_width):
                handle.write(seq[i : i + line_width] + "\n")


def write_fastq(records: list[tuple[str, str, str]], path: Path) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8") as handle:
        for name, seq, qual in records:
            handle.write(f"@{name}\n{seq}\n+\n{qual}\n")


def write_matrix_market(matrix: np.ndarray, path: Path) -> None:
    ensure_dir(path.parent)
    rows, cols = np.nonzero(matrix)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("%%MatrixMarket matrix coordinate integer general\n")
        handle.write("% generated by BioMind benchmark fixture generator\n")
        handle.write(f"{matrix.shape[0]} {matrix.shape[1]} {len(rows)}\n")
        for r, c in zip(rows, cols):
            handle.write(f"{r + 1} {c + 1} {int(matrix[r, c])}\n")


def mutate_dna(seq: str, rng: np.random.Generator, error_rate: float) -> str:
    chars = np.array(list(seq))
    mask = rng.random(len(chars)) < error_rate
    for i in np.where(mask)[0]:
        choices = DNA_ALPHABET[DNA_ALPHABET != chars[i]]
        chars[i] = rng.choice(choices)
    return "".join(chars.tolist())


def mutate_protein(seq: str, rng: np.random.Generator, mutation_rate: float) -> str:
    chars = np.array(list(seq))
    mask = rng.random(len(chars)) < mutation_rate
    for i in np.where(mask)[0]:
        choices = AA_ALPHABET[AA_ALPHABET != chars[i]]
        chars[i] = rng.choice(choices)
    return "".join(chars.tolist())


def simulate_scrna(cfg: FixtureConfig) -> None:
    rng = np.random.default_rng(cfg.seed + 1)
    out = ensure_dir(cfg.outdir / "scrna" / "toy_10x")

    n_genes = 320
    n_cells = 180
    n_clusters = 3
    genes = [f"Gene{i:03d}" for i in range(1, n_genes + 1)]
    gene_ids = [f"BMGENE{i:05d}" for i in range(1, n_genes + 1)]
    barcodes = [f"BM_CELL_{i:03d}-1" for i in range(1, n_cells + 1)]
    clusters = np.repeat(np.arange(n_clusters), n_cells // n_clusters)
    conditions = np.array(["ctrl" if i % 2 == 0 else "stim" for i in range(n_cells)])

    base_mean = rng.gamma(shape=1.6, scale=1.4, size=n_genes)
    mean = np.tile(base_mean[:, None], (1, n_cells))
    marker_rows: list[dict[str, object]] = []
    for cluster in range(n_clusters):
        marker_idx = np.arange(cluster * 18, cluster * 18 + 18)
        mean[np.ix_(marker_idx, clusters == cluster)] *= 7.0
        for idx in marker_idx[:8]:
            marker_rows.append(
                {
                    "cluster": f"cluster_{cluster}",
                    "gene_id": gene_ids[idx],
                    "gene_name": genes[idx],
                    "expected_log2fc": round(float(math.log2(7.0)), 3),
                }
            )
    stim_idx = np.arange(70, 90)
    mean[np.ix_(stim_idx, conditions == "stim")] *= 3.5

    dispersion = 1.2
    p = dispersion / (dispersion + mean)
    counts = rng.negative_binomial(dispersion, p).astype(int)
    keep = counts.sum(axis=1) > 0
    counts = counts[keep]
    genes = [g for g, k in zip(genes, keep) if k]
    gene_ids = [g for g, k in zip(gene_ids, keep) if k]

    write_matrix_market(counts, out / "matrix.mtx")
    pd.DataFrame({"gene_id": gene_ids, "gene_name": genes, "feature_type": "Gene Expression"}).to_csv(
        out / "features.tsv", sep="\t", header=False, index=False
    )
    pd.DataFrame({"barcode": barcodes}).to_csv(out / "barcodes.tsv", sep="\t", header=False, index=False)
    write_tsv(
        pd.DataFrame(
            {
                "barcode": barcodes,
                "sample_id": ["toy_pbmc"] * n_cells,
                "condition": conditions,
                "truth_cluster": [f"cluster_{x}" for x in clusters],
                "n_counts": counts.sum(axis=0),
                "n_features": (counts > 0).sum(axis=0),
            }
        ),
        out / "cell_metadata.tsv",
    )
    write_tsv(pd.DataFrame(marker_rows), out / "truth_markers.tsv")

    manifest = {
        "project_name": "biomind_toy_scrna",
        "species": "human",
        "input_mode": "10x_mtx",
        "sample_id": "toy_pbmc",
        "input_path": str(out.as_posix()),
        "output_dir": str((cfg.outdir / "scrna" / "outputs" / "toy_pbmc").as_posix()),
        "qc": {
            "min_features": 20,
            "max_features": 280,
            "min_counts": 30,
            "max_counts": 5000,
            "max_percent_mt": 25,
        },
    }
    (cfg.outdir / "scrna" / "toy_10x_manifest.yaml").write_text(
        "\n".join(
            [
                f"project_name: {manifest['project_name']}",
                f"species: {manifest['species']}",
                f"input_mode: {manifest['input_mode']}",
                f"sample_id: {manifest['sample_id']}",
                f"input_path: {manifest['input_path']}",
                f"output_dir: {manifest['output_dir']}",
                "",
                "qc:",
                *[f"  {k}: {v}" for k, v in manifest["qc"].items()],
                "",
            ]
        ),
        encoding="utf-8",
    )


def simulate_crop_breeding(cfg: FixtureConfig) -> None:
    rng = np.random.default_rng(cfg.seed + 2)
    out = ensure_dir(cfg.outdir / "crop_breeding")
    n_samples = 60
    n_markers = 80
    samples = [f"BM_CROP_{i:03d}" for i in range(1, n_samples + 1)]
    markers = [f"SNP_{i:04d}" for i in range(1, n_markers + 1)]

    mafs = rng.uniform(0.08, 0.48, size=n_markers)
    genotype = np.vstack([rng.binomial(2, maf, size=n_samples) for maf in mafs]).T
    genotype_df = pd.DataFrame(genotype, columns=markers)
    genotype_df.insert(0, "sample_id", samples)
    write_tsv(genotype_df, out / "genotype_matrix.tsv")

    effect_idx = np.array([2, 7, 13, 21, 34, 48, 61, 75])
    effects = np.zeros(n_markers)
    effects[effect_idx] = rng.normal(0.0, 1.0, size=len(effect_idx))
    trait = 50 + genotype @ effects + rng.normal(0, 1.5, n_samples)
    family = [f"FAM_{(i % 6) + 1}" for i in range(n_samples)]
    phenotype_df = pd.DataFrame(
        {
            "sample_id": samples,
            "trait_yield": np.round(trait, 3),
            "family": family,
            "year": np.where(np.arange(n_samples) < 30, 2025, 2026),
        }
    )
    write_tsv(phenotype_df, out / "phenotype.tsv")

    chroms = [f"Chr{(i % 5) + 1:02d}" for i in range(n_markers)]
    pos = np.array([(i % 16) * 75000 + 10000 for i in range(n_markers)])
    marker_anno = pd.DataFrame(
        {
            "marker_id": markers,
            "chrom": chroms,
            "pos": pos,
            "gene_id": [f"GENE_{(i % 40) + 1:04d}" for i in range(n_markers)],
        }
    )
    write_tsv(marker_anno, out / "marker_annotation.tsv")

    noise_p = rng.uniform(0.05, 1.0, size=n_markers)
    pvalues = np.minimum(noise_p, 10 ** (-(np.abs(effects) * 3.5 + rng.uniform(0.5, 1.5, n_markers))))
    gwas_df = marker_anno.copy()
    gwas_df["beta"] = np.round(effects + rng.normal(0, 0.05, n_markers), 5)
    gwas_df["pvalue"] = np.round(pvalues, 8)
    write_tsv(gwas_df, out / "gwas_summary.tsv")

    marker_effects = pd.DataFrame(
        {
            "marker_id": [markers[i] for i in effect_idx],
            "effect_allele": ["ALT"] * len(effect_idx),
            "effect": np.round(effects[effect_idx], 5),
            "trait_direction": ["high"] * len(effect_idx),
        }
    )
    write_tsv(marker_effects, out / "marker_effects.tsv")

    envs = ["loc_A", "loc_B", "loc_C"]
    env_shift = {"loc_A": 0.0, "loc_B": -2.5, "loc_C": 1.8}
    slope = genotype[:, effect_idx[:3]].sum(axis=1) * 0.18 + rng.normal(0, 0.15, n_samples)
    rows = []
    for sample_i, sample in enumerate(samples):
        for env in envs:
            rows.append(
                {
                    "sample_id": sample,
                    "environment": env,
                    "trait_yield": round(float(trait[sample_i] + env_shift[env] + slope[sample_i] * (envs.index(env) - 1)), 3),
                    "family": family[sample_i],
                }
            )
    write_tsv(pd.DataFrame(rows), out / "phenotype_multi_environment.tsv")

    weather_rows = []
    for env in envs:
        for day in range(1, 31):
            weather_rows.append(
                {
                    "environment": env,
                    "day_after_sowing": day,
                    "temperature_c": round(22 + envs.index(env) * 1.5 + math.sin(day / 4) * 3 + rng.normal(0, 0.5), 3),
                    "rainfall_mm": round(max(0, rng.gamma(1.4, 2.0) - envs.index(env)), 3),
                    "radiation_mj": round(15 + math.cos(day / 5) * 2 + rng.normal(0, 0.4), 3),
                }
            )
    write_tsv(pd.DataFrame(weather_rows), out / "environment_timeseries.tsv")
    write_tsv(
        pd.DataFrame(
            [
                {"stage": "vegetative", "start_day": 1, "end_day": 12},
                {"stage": "flowering", "start_day": 13, "end_day": 22},
                {"stage": "grain_fill", "start_day": 23, "end_day": 30},
            ]
        ),
        out / "growth_stage_window.tsv",
    )

    genes = [f"GENE_{i:04d}" for i in range(1, 121)]
    expr = rng.normal(8, 1.0, size=(len(genes), n_samples))
    for j, idx in enumerate(effect_idx[:6]):
        expr[j, :] += genotype[:, idx] * 0.7
    expr_df = pd.DataFrame(expr, columns=samples)
    expr_df.insert(0, "gene_id", genes)
    write_tsv(expr_df.round(4), out / "expression_matrix.tsv")

    metabolites = [f"MET_{i:03d}" for i in range(1, 31)]
    metab = rng.normal(0, 1.0, size=(len(metabolites), n_samples))
    for j in range(6):
        metab[j, :] += genotype[:, effect_idx[j]] * 0.45
    metab_df = pd.DataFrame(metab, columns=samples)
    metab_df.insert(0, "metabolite_id", metabolites)
    write_tsv(metab_df.round(4), out / "metabolite_matrix.tsv")

    ortholog_rows = [
        {"species": "maize", "gene_id": gene, "ortholog_species": "rice", "ortholog_gene_id": f"Os{idx:05d}"}
        for idx, gene in enumerate(genes[:80], 1)
    ]
    write_tsv(pd.DataFrame(ortholog_rows), out / "species_ortholog_table.tsv")
    write_tsv(
        pd.DataFrame(
            {
                "sample_id": samples,
                "condition": np.where(np.array(trait) > np.median(trait), "high_trait", "low_trait"),
                "tissue": ["leaf"] * n_samples,
            }
        ),
        out / "condition_metadata.tsv",
    )

    pav_genes = [f"PAV_GENE_{i:04d}" for i in range(1, 41)]
    pav = rng.binomial(1, 0.75, size=(len(pav_genes), n_samples))
    pav_df = pd.DataFrame(pav, columns=samples)
    pav_df.insert(0, "gene_id", pav_genes)
    write_tsv(pav_df, out / "pangenome_gene_presence_absence.tsv")

    write_crop_vcf(samples[:20], markers[:24], chroms[:24], pos[:24], genotype[:20, :24], out / "toy_samples.vcf")
    write_sv_vcf(samples[:20], out / "sv.vcf", rng)


def write_crop_vcf(samples: list[str], markers: list[str], chroms: list[str], positions: np.ndarray, genotype: np.ndarray, path: Path) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("##fileformat=VCFv4.2\n")
        handle.write("##source=BioMindFixtureGenerator\n")
        handle.write("##FORMAT=<ID=GT,Number=1,Type=String,Description=\"Genotype\">\n")
        handle.write("#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\t" + "\t".join(samples) + "\n")
        for j, marker in enumerate(markers):
            gts = []
            for value in genotype[:, j]:
                if value == 0:
                    gts.append("0/0")
                elif value == 1:
                    gts.append("0/1")
                else:
                    gts.append("1/1")
            handle.write(f"{chroms[j]}\t{int(positions[j])}\t{marker}\tA\tG\t.\tPASS\t.\tGT\t" + "\t".join(gts) + "\n")


def write_sv_vcf(samples: list[str], path: Path, rng: np.random.Generator) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("##fileformat=VCFv4.2\n")
        handle.write("##source=BioMindFixtureGenerator\n")
        handle.write("##ALT=<ID=DEL,Description=\"Deletion\">\n")
        handle.write("##ALT=<ID=DUP,Description=\"Duplication\">\n")
        handle.write("##FORMAT=<ID=GT,Number=1,Type=String,Description=\"Genotype\">\n")
        handle.write("#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\t" + "\t".join(samples) + "\n")
        for i in range(1, 11):
            svtype = "DEL" if i % 2 else "DUP"
            gts = rng.choice(["0/0", "0/1", "1/1"], size=len(samples), p=[0.55, 0.35, 0.10])
            info = f"SVTYPE={svtype};END={100000 + i * 5000 + 1200}"
            handle.write(f"Chr{(i % 5) + 1:02d}\t{100000 + i * 5000}\tSV_{i:03d}\tN\t<{svtype}>\t.\tPASS\t{info}\tGT\t" + "\t".join(gts) + "\n")


def simulate_sequence(cfg: FixtureConfig) -> None:
    rng = np.random.default_rng(cfg.seed + 3)
    out = ensure_dir(cfg.outdir / "sequence")
    targets: list[tuple[str, str]] = []
    queries: list[tuple[str, str]] = []
    expected = []
    for i in range(1, 9):
        base = "".join(rng.choice(AA_ALPHABET, size=160 + i * 3).tolist())
        target_id = f"TARGET_PROT_{i:03d}"
        targets.append((target_id, base))
        if i <= 5:
            query_id = f"QUERY_PROT_{i:03d}"
            query = mutate_protein(base, rng, 0.04 + i * 0.01)
            queries.append((query_id, query))
            expected.append(
                {
                    "qseqid": query_id,
                    "expected_top_hit": target_id,
                    "expected_identity_floor": round(100 * (1 - (0.04 + i * 0.01)) - 3, 2),
                    "expected_qcov_floor": 90,
                }
            )
    queries.append(("QUERY_NO_HIT_001", "".join(rng.choice(AA_ALPHABET, size=95).tolist())))
    write_fasta(targets, out / "target_proteins.fasta")
    write_fasta(queries, out / "query_proteins.fasta")
    write_tsv(pd.DataFrame(expected), out / "expected_top_hits.tsv")

    nuc = "".join(rng.choice(DNA_ALPHABET, size=650).tolist())
    write_fasta([("PUBLIC_UNKNOWN_NT_001", mutate_dna(nuc, rng, 0.02))], out / "public_unknown_nucleotide.fasta")


