@pytest.mark.parametrize("role", ["reference_preparation_evidence", "unknown_second_bundle"])
def test_v2_only_excludes_explicit_engineering_evidence_role(tmp_path, role):
    task_id, bundle = _setup(tmp_path)
    _bundle(bundle)
    _set_uri(bundle, reference_file_uri(bundle / "reference.fa").encode("ascii"))
    plan = load_plan_state(tmp_path, task_id)
    step = plan["steps"][0]
    for effect in (step, step["step_effect"]):
        effect["produces_observations"][0]["predicate"]["parser_id"] = REFERENCE_BUNDLE_FINAL_URI_PARSER_ID
    step["outputs"].append("engineering-output")
    plan["plan_artifacts"]["engineering-output"] = {
        "role": role, "object_kind": "directory", "canonical_path": str(tmp_path / "evidence")}
    if role == "reference_preparation_evidence":
        assert build_reference_bundle_receipt(plan, step)["value"]
    else:
        with pytest.raises(ReferenceBundleError, match="REFERENCE_BUNDLE_OUTPUT_SCOPE_UNVERIFIABLE"):
            build_reference_bundle_receipt(plan, step)


