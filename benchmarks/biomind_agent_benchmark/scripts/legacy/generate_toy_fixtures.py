def write_bed(records: list[tuple[str, int, int, str]], path: Path) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8") as handle:
        for chrom, start, end, name in records:
            handle.write(f"{chrom}\t{start}\t{end}\t{name}\n")


def boundaries_from_domains(domains: list[tuple[str, int, int, str]], prefix: str) -> list[tuple[str, int, int, str]]:
    records = []
    idx = 1
    seen: set[tuple[str, int]] = set()
    for chrom, start, end, _ in domains:
        for pos in (start, end):
            key = (chrom, pos)
            if pos > 0 and key not in seen:
                records.append((chrom, pos, pos + 1, f"{prefix}_{idx}"))
                idx += 1
                seen.add(key)
    return records


